#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Pixel {
    pub x: u8,
    pub y: u8,
    pub color: [u8; 3],
}

pub fn frame_grid(bird: BirdId, frame: Frame) -> &'static [&'static str; ROWS] {
    match bird {
        BirdId::Lennie => &LENNIE[frame as usize],
        BirdId::Meggie => &MEGGIE[frame as usize],
    }
}

pub fn pixels(bird: BirdId, frame: Frame) -> impl Iterator<Item = Pixel> {
    frame_grid(bird, frame)
        .iter()
        .enumerate()
        .flat_map(move |(y, row)| {
            row.bytes().enumerate().filter_map(move |(x, cell)| {
                color(cell).map(|color| Pixel {
                    x: x as u8,
                    y: y as u8,
                    color,
                })
            })
        })
}

pub fn color(cell: u8) -> Option<[u8; 3]> {
    match cell {
        b'o' => Some([0x1F, 0x4F, 0xBF]),
        b'b' => Some([0x4F, 0x8D, 0xFF]),
        b'l' => Some([0x9C, 0xC4, 0xFF]),
        b'w' => Some([0xFF, 0xFF, 0xFF]),
        b'k' => Some([0x1A, 0x1A, 0x2E]),
        b'f' => Some([0xBF, 0xE0, 0xFF]),
        b'p' => Some([0xFF, 0x9E, 0xC4]),
        b'y' => Some([0xF2, 0xA3, 0x3A]),
        b'n' => Some([0xC9, 0x77, 0x1F]),
        b'r' => Some([0xFF, 0x6F, 0xA3]),
        b'd' => Some([0xD9, 0xD2, 0xC2]),
        b'g' => Some([0x3E, 0x7D, 0x3E]),
        b'c' => Some([0xDD, 0xF3, 0xC9]),
        b's' => Some([0xB9, 0xD9, 0x8C]),
        b'e' => Some([0x8A, 0x5A, 0x2B]),
        b'O' => Some([0x4A, 0x4A, 0x58]),
        b'G' => Some([0x9A, 0x9A, 0xA6]),
        b'F' => Some([0xD6, 0xD6, 0xDE]),
        b'W' => Some([0xB8, 0xB8, 0xC4]),
        b'Y' => Some([0xF5, 0xC5, 0x42]),
        b'K' => Some([0x1A, 0x1A, 0x2E]),
        b'H' => Some([0xFF, 0xFF, 0xFF]),
        b'B' => Some([0xD9, 0x8A, 0x2B]),
        b'N' => Some([0xA8, 0x64, 0x1A]),
        b'L' => Some([0xD9, 0x8A, 0x2B]),
        b'P' => Some([0xF4, 0xB6, 0xC2]),
        b'E' => Some([0x8A, 0x5A, 0x2B]),
        b'V' => Some([0x3E, 0x7D, 0x3E]),
        b'U' => Some([0xDD, 0xF3, 0xC9]),
        b'S' => Some([0xB9, 0xD9, 0x8C]),
        _ => None,
    }
}

