#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn artwork_has_valid_cells_and_fixed_dimensions() {
        for bird in BirdId::ALL {
            for frame in Frame::ALL {
                let grid = frame_grid(bird, frame);
                assert_eq!(grid.len(), ROWS);
                for row in grid {
                    assert_eq!(row.len(), COLUMNS);
                    for cell in row.bytes() {
                        assert!(cell == b'.' || color(cell).is_some());
                    }
                }
                assert!(pixels(bird, frame).count() > 100);
            }
        }
    }
    #[test]
    fn unknown_bird_preserves_lennie_compatibility() {
        assert_eq!(BirdId::from_id("unknown"), BirdId::Lennie);
        assert_eq!(BirdId::from_id(" MEGGIE "), BirdId::Meggie);
    }
}
