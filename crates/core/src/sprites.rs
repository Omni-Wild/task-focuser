//! Original pixel artwork, transcribed without alteration from the Windows companion.

pub const CELL_SIZE: u8 = 3;
pub const COLUMNS: usize = 22;
pub const ROWS: usize = 16;
pub const WIDTH: f64 = (COLUMNS * CELL_SIZE as usize) as f64;
pub const HEIGHT: f64 = (ROWS * CELL_SIZE as usize) as f64;

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
pub enum BirdId {
    #[default]
    Lennie,
    Meggie,
}

impl BirdId {
    pub const ALL: [Self; 2] = [Self::Lennie, Self::Meggie];
    pub fn from_id(id: &str) -> Self {
        if id.trim().eq_ignore_ascii_case("meggie") {
            Self::Meggie
        } else {
            Self::Lennie
        }
    }
    pub const fn id(self) -> &'static str {
        match self {
            Self::Lennie => "lennie",
            Self::Meggie => "meggie",
        }
    }
    pub const fn default_name(self) -> &'static str {
        match self {
            Self::Lennie => "Lennie",
            Self::Meggie => "Meggie",
        }
    }
}

