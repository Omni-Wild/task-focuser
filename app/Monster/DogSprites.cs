// Rori the Japanese spitz (SPEC-round6 2.1), drawn in Lennie's idiom rather than as a portrait: his boxy,
// round-cornered body wider than tall and his big front-on face (the two large eyes, white with dark
// pupils, the same size and place as his, a soft grey rim around the white so it shows on white fur), in
// white with only the clearest dog markers: two pointed ears on top (one pink cell each), a black nose at
// the right of the face where his beak is, a small curled tail on the left and four stubby legs. A mascot,
// read at 1x, nothing anatomical. The same grid format as Sprites.cs and OwlSprites.cs, so the art can be
// read by eye and parsed by a regex (one Legend entry per line, one quoted row per line): 22 x 16 cells,
// the same CellSize, feet on row 15, facing right (the nose points right; FlipX mirrors her). Her Legend
// keys are digits and symbols so they never collide with Lennie's lowercase or Meggie's uppercase ones
// (the sprite view merges the legends into one brush map). The outline is a soft blue-grey, so the white
// dog reads on a white note, on the bar and against a dark desktop alike. The sitting frames share one
// body (the legs, the bottom rows), so a frame swap never makes her jump; the front toe is cell 16.
